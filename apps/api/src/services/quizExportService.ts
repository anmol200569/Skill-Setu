import { jsPDF } from 'jspdf';
import { Quiz, QuizQuestionGenerated } from '@skill-setu/shared';

export function generateQuizPdf(quiz: {
  title: string;
  description: string;
  difficulty: string;
  language: string;
  questions: {
    questionText: string;
    type: string;
    options: { id: string; text: string }[];
    correctAnswers: string[];
    explanation: string;
    topicTag: string;
  }[];
}): Buffer {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const margin = 20;
  let cursorY = margin;
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxLineWidth = pageWidth - margin * 2;

  // Header Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(26, 26, 24); // #1A1A18
  doc.text(quiz.title, margin, cursorY);
  cursorY += 8;

  // Subtitle / Meta
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Difficulty: ${quiz.difficulty.toUpperCase()} | Questions: ${quiz.questions.length} | Generated by Skill Setu`, margin, cursorY);
  cursorY += 12;

  // Horizontal line
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 8;

  // Questions Section
  quiz.questions.forEach((q, idx) => {
    // Check if new page needed
    if (cursorY > pageHeight - 40) {
      doc.addPage();
      cursorY = margin;
    }

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(26, 26, 24);

    const questionLines = doc.splitTextToSize(`Q${idx + 1}. ${q.questionText} [${q.topicTag}]`, maxLineWidth);
    doc.text(questionLines, margin, cursorY);
    cursorY += questionLines.length * 5 + 3;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(60, 60, 60);

    const alphabet = ['A', 'B', 'C', 'D', 'E', 'F'];
    q.options.forEach((opt, optIdx) => {
      if (cursorY > pageHeight - 20) {
        doc.addPage();
        cursorY = margin;
      }
      const prefix = alphabet[optIdx] || `${optIdx + 1}`;
      const optLines = doc.splitTextToSize(`   ${prefix}) ${opt.text}`, maxLineWidth - 5);
      doc.text(optLines, margin + 2, cursorY);
      cursorY += optLines.length * 4.5 + 1;
    });

    cursorY += 6;
  });

  // Page break for Answer Key
  doc.addPage();
  cursorY = margin;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(194, 65, 12); // #C2410C
  doc.text('Answer Key & Explanations', margin, cursorY);
  cursorY += 10;

  quiz.questions.forEach((q, idx) => {
    if (cursorY > pageHeight - 35) {
      doc.addPage();
      cursorY = margin;
    }

    const alphabet = ['A', 'B', 'C', 'D', 'E', 'F'];
    const correctTexts = q.options
      .filter((opt) => q.correctAnswers.includes(opt.id))
      .map((opt) => {
        const optIndex = q.options.findIndex((o) => o.id === opt.id);
        const letter = alphabet[optIndex] || '';
        return `${letter}) ${opt.text}`;
      })
      .join(', ');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(26, 26, 24);
    doc.text(`Q${idx + 1}: Correct Answer: ${correctTexts}`, margin, cursorY);
    cursorY += 5;

    doc.setFont('helvetica', 'italic');
    doc.setFontSize(9);
    doc.setTextColor(80, 80, 80);
    const expLines = doc.splitTextToSize(`Explanation: ${q.explanation}`, maxLineWidth);
    doc.text(expLines, margin, cursorY);
    cursorY += expLines.length * 4 + 6;
  });

  const arrayBuffer = doc.output('arraybuffer');
  return Buffer.from(arrayBuffer);
}
